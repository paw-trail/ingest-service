package com.pawtrail.ingest.domain.enums;

/**
 * 수집 실행의 상태입니다.
 *
 * 마친 상태 넷 가운데 재개 지점을 물려주는 것은 둘입니다.
 * 우리가 상황을 보고 스스로 멈춘 것만 이어받고,
 * 예상하지 못한 오류로 죽은 것은 처음부터 다시 받습니다.
 */
public enum RunStatus {

    // 실행 중입니다. 같은 소스로 또 부르면 거절합니다.
    RUNNING,

    // 끝까지 마쳤습니다.
    DONE,

    // 예상하지 못한 오류로 멈췄습니다. 원인은 error_message 에 있습니다.
    //
    // 다음 실행이 이 재개 지점을 물려받지 않습니다.
    // 무엇이 잘못됐는지 모르는 상태라 그대로 이어받으면 문제가 난 구간을 조용히 건너뜁니다.
    // 이미 쓴 허용량을 다시 쓰게 되지만, 무엇을 빠뜨렸는지 모르는 채로 두는 것보다 낫습니다.
    FAILED,

    // 일일 호출 허용량에 걸려 멈췄습니다. 실패가 아닙니다.
    //
    // 대상이 1,079건인데 상세 오퍼레이션마다 하루 1,000건이라
    // 한 번에 끝나지 않는 것이 정상입니다.
    // 다음 실행이 progress 의 cursor 에서 이어받습니다.
    QUOTA_STOPPED,

    // 더 진행하는 것이 낭비라고 판단해 스스로 멈췄습니다. 실패가 아닙니다.
    //
    // 한 건씩 실패해 건너뛰다가 연달아 실패하면 소스가 멈췄거나 우리 요청이 잘못된 것입니다.
    // 계속 부르면 남은 허용량을 전부 헛되이 씁니다.
    //
    // 우리가 상황을 보고 멈춘 것이고 그때까지 저장한 것은 멀쩡하므로
    // 다음 실행이 재개 지점을 물려받습니다.
    // 그러지 않으면 소스가 잠깐 멈춘 대가로 그날 쓴 허용량이 통째로 사라집니다.
    INTERRUPTED
}
