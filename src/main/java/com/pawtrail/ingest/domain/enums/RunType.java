package com.pawtrail.ingest.domain.enums;

/**
 * 실행의 종류입니다.
 *
 * 앞의 둘은 바깥에서 받아 오는 방법이 다른 것이고 마지막 하나는 하는 일 자체가 다릅니다.
 * 셋을 한 값으로 둔 이유는 실행 기록이 하나이기 때문입니다.
 * 언제 시작해 몇 건을 다루고 어떻게 끝났는지를 같은 표에 남깁니다.
 */
public enum RunType {

    // 전량을 받습니다. 처음 적재하거나 스키마가 바뀌어 다시 받을 때 씁니다.
    FULL,

    // 소스가 알려준 수정 시각이 우리가 가진 값보다 새로운 것만 받습니다.
    //
    // 상세 호출에 일일 쿼터가 걸려 있어 이 구분이 실질적인 의미를 가집니다.
    // 목록은 매번 전량을 받아도 부담이 없지만 상세는 건당 한 번씩 쿼터를 씁니다.
    INCREMENTAL,

    // 이미 받아 둔 것을 장소 서비스로 넘기고 돌려받은 식별자를 채움
    //
    // 바깥을 부르지 않음.  우리 표를 읽어 다른 서비스에 보낼 뿐임
    // 그래서 호출 허용량과 무관하고 몇 번을 돌려도 같은 결과가 됨
    //
    // 수집이 끝나면 자동으로 이어 붙이지 않고 따로 부르게 두었음
    // 그러면 수집만 다시 하고 싶을 때 넘기기까지 딸려 오고
    // 무엇을 언제 내보낼지를 사람이 정하지 못하게 됨
    LINK
}
