-- 같은 소스가 동시에 두 번 실행되는 것을 막습니다.
--
-- 트리거는 실행 중인지 먼저 확인하지만 그것만으로는 막히지 않습니다.
-- 두 요청이 같은 순간에 들어오면 둘 다 없음을 보고 지나가 각자 실행을 만들 수 있습니다.
-- 그러면 같은 소스를 두 번 수집하면서 일일 호출 허용량을 두 배로 쓰고,
-- 둘 다 한도에 못 미쳐 멈춰 어느 쪽도 끝내지 못한 채 그날 몫이 사라집니다.
-- 호출 허용량은 되돌릴 수 없는 자원이라 나중에 알아채도 복구할 방법이 없습니다.
--
-- 부분 유일 인덱스입니다. 상태가 RUNNING 인 행만 대상으로 합니다.
-- 실행 기록은 소스마다 여러 건 쌓이는 것이 정상이므로 표 전체에 걸면 안 됩니다.
-- 공통 대역의 outbox 가 발행 전인 행만 인덱스에 담는 것과 같은 방식입니다.
--
-- 대가를 알고 씁니다.
-- 실행이 마감되지 못하고 RUNNING 인 채 남으면 그 소스가 다시 시작되지 않습니다.
-- 프로세스가 죽는 경우가 그렇습니다.
-- 사람이 상태를 손으로 바로잡아야 하며, 오래 남은 실행을 정리하는 방법은
-- 실제로 겪어 본 뒤에 정합니다.

CREATE UNIQUE INDEX uq_ingest_run_running
    ON ingest_run (source) WHERE status = 'RUNNING';
